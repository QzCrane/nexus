// goal: Generate _generated-tool-loader.ts
// eff: One memoized import authority shared by hover preload and lazy rendering

import path from 'node:path';
import { OUTPUT_LOADER } from './config.ts';
import {
	detectPanelExport,
	emitGeneratedFile,
	toPascalCase,
	type GenerationMode,
} from './utils.ts';
import { isReleaseAdmitted } from '../../apps/extension-halo/src/kernel/registry/release-admission.ts';

/**
 * Generate lazy loader TypeScript file. Catalog-only modules keep metadata in
 * the canonical registry but are absent from the physical release import graph.
 */
export function generateLoader(allModules, manifestsMap, mode: GenerationMode = 'write') {
	const admittedModules = allModules.filter((module) =>
		isReleaseAdmitted(manifestsMap.get(module.id)?.status));
	const panelModules = admittedModules.filter((module) => module.pluginType !== 'script' && module.panelPath);
	const scriptModules = admittedModules.filter((module) => module.pluginType === 'script');

	const header = `// AUTO-GENERATED - DO NOT EDIT
// Generated by: bun run generate-registry
// Source: release-admitted tools/scripts/system only

import { lazy } from 'react';

function memoizePanelLoader<T>(load: () => Promise<T>): () => Promise<T> {
\tlet pending: Promise<T> | null = null;
\treturn () => {
\t\tif (pending) return pending;
\t\tconst next = load().catch((error: unknown) => {
\t\t\tif (pending === next) pending = null;
\t\t\tthrow error;
\t\t});
\t\tpending = next;
\t\treturn next;
\t};
}

`;

	// Build tool-to-import map once. Both explicit preload and renderer lazy()
	// consume the same memoized promise so no renderer-private fields are needed.
	const loaderEntries = panelModules.map((module) => {
		const exportName = detectPanelExport(module.panelPath) || `${toPascalCase(module.id)}Panel`;
		const folder = module.dirType === 'system' ? 'system' : (module.dirType === 'scripts' ? 'scripts' : 'tools');
		const normalizedPanelDir = path.dirname(module.panelPath).replace(/\\/g, '/');
		const searchPattern = `src/${folder}/${module.dirName}`;
		const baseIndex = normalizedPanelDir.indexOf(searchPattern);
		const relativePart = baseIndex >= 0
			? `${normalizedPanelDir.substring(baseIndex + `src/${folder}/`.length)}/panel`
			: `${module.dirName}/panel`;
		return `\t'${module.id}': memoizePanelLoader(() => import('../${folder}/${relativePart}').then(m => ({ default: m.${exportName} })))`;
	});

	const panelEntries = panelModules.map((module) => {
		const access = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(module.id)
			? `.${module.id}`
			: `['${module.id}']`;
		return `\t'${module.id}': lazy(generatedToolLoaders${access})`;
	});

	const content = `${header}export const generatedToolLoaders = {
${loaderEntries.join(',\n')}
} as const;

export const generatedToolPanels = {
${panelEntries.join(',\n')}
} as const;

export type LoadableToolId = keyof typeof generatedToolLoaders;

// Release-admitted script plugin IDs (no React panel, uses UserScripts engine)
export const SCRIPT_PLUGIN_IDS: readonly string[] = [${scriptModules.map((module) => `'${module.id}'`).join(', ')}];
`;

	emitGeneratedFile(OUTPUT_LOADER, content, mode, 'loader');
}
