// goal: Generate HALO registry artifacts
// eff: Canonical full catalog registry plus release-admitted runtime projections

import {
	OUTPUT_BACKGROUND_ACTIVE,
	OUTPUT_REGISTRY,
	OUTPUT_SCRIPT_RUNTIME,
} from './config.ts';
import { emitGeneratedFile, type GenerationMode } from './utils.ts';
import {
	hasReleaseSurface,
	type ReleaseAdmissionModule,
} from './release-admission.ts';

/**
 * Generate the canonical full registry. Catalog metadata intentionally remains
 * broader than the physical release payload; executable admission is a
 * separate generated authority.
 */
export function generateRegistry(
	allModules,
	manifestsMap,
	releaseVersion,
	mode: GenerationMode = 'write',
) {
	const header = `// AUTO-GENERATED - DO NOT EDIT
// Generated by: bun run generate-registry
// Schema: pluginType ('tool'|'script'|'system') + functional category

import type { ToolCategory } from '../../i18n/types';
import type { PluginType, ScriptType } from './taxonomy';

// Background consumption profile
export interface BackgroundProfile {
\tmechanism: 'interval_fast' | 'interval_slow' | 'raf_active' | 'raf_idle' | 'event_listener' | 'storage_listener' | 'message_listener' | 'wheel_listener' | 'copy_listener' | 'mutation_observer' | 'service_worker' | 'content_script' | 'userscript';
\tfrequency: string;
\tactiveOnly: boolean;
\tlevel: 'high' | 'medium' | 'low' | 'idle';
\tdescriptionKey: string;
\tsourceFile: string;
\tsourceAnchor: string;
\tsourceDetail?: string;
}

// Script plugin configuration (only for pluginType='script')
export interface ScriptConfig {
\ttype: ScriptType;
\trunAt: 'document_start' | 'document_end' | 'document_idle';
\tmatches: string[];
\texcludeMatches?: string[];
\tworld?: 'ISOLATED' | 'MAIN' | 'USER_SCRIPT';
}

// Unified catalog metadata. Physical release admission is generated separately.
export interface PluginMeta {
\tid: string;
\ticon: string;
\tpluginType: PluginType;
\tcategory: ToolCategory;
\tversion: string;
\tdistribution: 'bundled';
\tbuiltIn: boolean;
\tstatus?: 'ready' | 'beta' | 'coming' | 'disabled';
\tkeywords: string[];
\tpermissions?: string[];
\tbackground?: BackgroundProfile;
\tscript?: ScriptConfig; // Only for script plugins
}
`;

	const generateEntry = (module) => {
		const manifest = manifestsMap.get(module.id);
		const keywords = manifest.keywords ? JSON.stringify(manifest.keywords) : '[]';
		const permissions = manifest.permissions?.length
			? JSON.stringify(manifest.permissions)
			: 'undefined';
		const background = manifest.background
			? JSON.stringify(manifest.background)
			: 'undefined';
		const scriptConfig = manifest.script ? JSON.stringify(manifest.script) : 'undefined';
		return `\t{
\t\tid: '${manifest.id}',
\t\ticon: '${manifest.icon}',
\t\tpluginType: '${module.pluginType}',
\t\tcategory: '${manifest.category}',
\t\tversion: '${releaseVersion}',
\t\tdistribution: 'bundled',
\t\tbuiltIn: ${manifest.builtIn ?? false},
\t\tstatus: ${manifest.status ? `'${manifest.status}'` : 'undefined'},
\t\tkeywords: ${keywords},
\t\tpermissions: ${permissions},
\t\tbackground: ${background},
\t\tscript: ${scriptConfig},
\t}`;
	};

	const permissionMap = {};
	for (const module of allModules) {
		const manifest = manifestsMap.get(module.id);
		if (!manifest.permissions) continue;
		for (const permission of manifest.permissions) {
			if (!permissionMap[permission]) permissionMap[permission] = [];
			permissionMap[permission].push(module.id);
		}
	}

	const backgroundMap = {};
	for (const module of allModules) {
		const manifest = manifestsMap.get(module.id);
		if (manifest.background) backgroundMap[module.id] = manifest.background;
	}

	const content = `${header}
export const PLUGIN_REGISTRY: PluginMeta[] = [
${allModules.map(generateEntry).join(',\n')}
];

export const HALO_RELEASE_VERSION = '${releaseVersion}';

export const PLUGIN_IDS = [${allModules.map((module) => `'${module.id}'`).join(', ')}] as const;
export type PluginId = (typeof PLUGIN_IDS)[number];

// Runtime filters (SSOT)
export const getToolPlugins = () => PLUGIN_REGISTRY.filter((plugin) => plugin.pluginType === 'tool');
export const getScriptPlugins = () => PLUGIN_REGISTRY.filter((plugin) => plugin.pluginType === 'script');
export const getSystemPlugins = () => PLUGIN_REGISTRY.filter((plugin) => plugin.pluginType === 'system');
export const getUserPlugins = () => PLUGIN_REGISTRY.filter((plugin) => plugin.pluginType !== 'system');

export const PERMISSION_USAGE_MAP: Record<string, string[]> = ${JSON.stringify(permissionMap, null, 4)};

export const BACKGROUND_PROFILES_MAP: Record<string, BackgroundProfile> = ${JSON.stringify(backgroundMap, null, 4)};

export const BACKGROUND_PLUGIN_IDS = Object.keys(BACKGROUND_PROFILES_MAP);

// Legacy compatibility aliases
export const ALL_APPS = PLUGIN_REGISTRY;
export const USER_TOOL_REGISTRY = getUserPlugins();
export const SYSTEM_PLUGIN_REGISTRY = getSystemPlugins();
export type GeneratedToolMeta = PluginMeta;
export type GeneratedToolId = PluginId;
export const TOOL_IDS = PLUGIN_IDS;
`;

	emitGeneratedFile(OUTPUT_REGISTRY, content, mode, 'registry');
}

/**
 * Generate only release-admitted background/content/script runtime membership
 * plus activeOnly for startup consumers. Catalog-only modules may retain
 * background provenance in the full registry but cannot project as a live
 * service merely because their source exists.
 */
export function generateBackgroundActiveProjection(
	allModules,
	manifestsMap,
	admissionMap: ReadonlyMap<string, ReleaseAdmissionModule>,
	mode: GenerationMode = 'write',
) {
	const activeOnlyMap = {};
	for (const module of allModules) {
		const executable = hasReleaseSurface(admissionMap, module.id, 'panel')
			|| hasReleaseSurface(admissionMap, module.id, 'background-runtime')
			|| hasReleaseSurface(admissionMap, module.id, 'content-runtime')
			|| hasReleaseSurface(admissionMap, module.id, 'script-runtime');
		if (!executable) continue;
		const background = manifestsMap.get(module.id)?.background;
		if (background) activeOnlyMap[module.id] = background.activeOnly === true;
	}

	const content = `// AUTO-GENERATED - DO NOT EDIT
// Generated by: bun run generate-registry
// Compact release-admitted runtime projection; detailed provenance lives in _generated.ts.

export const BACKGROUND_ACTIVE_ONLY_MAP: Readonly<Record<string, boolean>> = Object.freeze(${JSON.stringify(activeOnlyMap, null, 4)});
export const BACKGROUND_PLUGIN_IDS = Object.freeze(Object.keys(BACKGROUND_ACTIVE_ONLY_MAP));
`;
	emitGeneratedFile(OUTPUT_BACKGROUND_ACTIVE, content, mode, 'background startup projection');
}

/**
 * Generate only script descriptors explicitly admitted to the release. Source
 * presence or a script manifest alone cannot install code into the browser.
 */
export function generateScriptRuntimeManifest(
	allModules,
	manifestsMap,
	admissionMap: ReadonlyMap<string, ReleaseAdmissionModule>,
	mode: GenerationMode = 'write',
) {
	const descriptors = allModules.flatMap((module) => {
		if (!hasReleaseSurface(admissionMap, module.id, 'script-runtime')) return [];
		const manifest = manifestsMap.get(module.id);
		if (!manifest?.script) return [];
		return [{
			id: manifest.id,
			pluginType: module.pluginType,
			builtIn: manifest.builtIn ?? false,
			script: manifest.script,
		}];
	});

	emitGeneratedFile(
		OUTPUT_SCRIPT_RUNTIME,
		`${JSON.stringify(descriptors, null, 2)}\n`,
		mode,
		`script runtime (${descriptors.length})`,
	);
}
