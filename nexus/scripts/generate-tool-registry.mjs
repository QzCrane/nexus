#!/usr/bin/env node
// goal: Auto-generate tool registry from manifest files
// eff: Scan tools/*/manifest.json → generate _generated.ts + loader + i18n

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const HALO_ROOT = path.resolve(__dirname, '../apps/extension-halo/src');
const TOOLS_DIR = path.join(HALO_ROOT, 'tools');
const OUTPUT_REGISTRY = path.join(HALO_ROOT, 'kernel/registry/_generated.ts');
const OUTPUT_LOADER = path.join(HALO_ROOT, 'components/_generated-tool-loader.ts');
const OUTPUT_I18N_EN = path.join(HALO_ROOT, 'i18n/locales/_generated-tools-en.ts');
const OUTPUT_I18N_ZH = path.join(HALO_ROOT, 'i18n/locales/_generated-tools-zh.ts');

// Discover tool directories with manifest.json
function discoverTools() {
	const toolDirs = fs.readdirSync(TOOLS_DIR, { withFileTypes: true })
		.filter(d => d.isDirectory())
		.map(d => d.name);
	
	const tools = [];
	for (const dir of toolDirs) {
		const manifestPath = path.join(TOOLS_DIR, dir, 'manifest.json');
		const panelPath = path.join(TOOLS_DIR, dir, 'panel.tsx');
		const localesPath = path.join(TOOLS_DIR, dir, 'locales');
		
		if (fs.existsSync(manifestPath) && fs.existsSync(panelPath)) {
			tools.push({ 
				id: dir, 
				manifestPath, 
				panelPath,
				hasEn: fs.existsSync(path.join(localesPath, 'en.ts')),
				hasZh: fs.existsSync(path.join(localesPath, 'zh.ts'))
			});
		}
	}
	return tools;
}

// Parse manifest.json file
function parseManifest(filePath) {
	try {
		const content = fs.readFileSync(filePath, 'utf-8');
		return JSON.parse(content);
	} catch (e) {
		console.warn(`⚠️ Failed to parse: ${filePath}`, e.message);
		return null;
	}
}

// Detect panel export name from panel.tsx content
function detectPanelExport(panelPath) {
	try {
		const content = fs.readFileSync(panelPath, 'utf-8');
		// Match patterns like: export const XxxPanel or export function XxxPanel
		const match = content.match(/export\s+(?:const|function)\s+(\w+Panel)/);
		if (match) return match[1];
		// Fallback: match named export
		const namedMatch = content.match(/export\s*{\s*(\w+Panel)\s*}/);
		if (namedMatch) return namedMatch[1];
	} catch { /* ignore */ }
	return null;
}

// Convert kebab-case to PascalCase (fallback)
function toPascalCase(str) {
	return str.split('-').map(s => s.charAt(0).toUpperCase() + s.slice(1)).join('');
}

// Generate registry file
function generateRegistry(tools, manifests) {
	const header = `// AUTO-GENERATED - DO NOT EDIT
// Generated by: pnpm generate-registry
// Source: tools/*/manifest.json

import type { ToolCategory } from '../../i18n/types';

// Generated tool manifest interface
export interface GeneratedToolMeta {
	id: string;
	icon: string;
	category: ToolCategory;
	size: number;
	builtIn: boolean;
	system: boolean; // true = system functionality (settings, module-store), not counted as tool
	keywords: string[];
	features?: { contextMenu?: boolean; contentScript?: boolean; offscreen?: boolean };
	dependencies?: string[];
}
`;

	const entries = manifests.map(m => {
		const features = m.features ? JSON.stringify(m.features) : 'undefined';
		const keywords = m.keywords ? JSON.stringify(m.keywords) : '[]';
		const deps = m.dependencies ? JSON.stringify(m.dependencies) : 'undefined';
		return `\t{
		id: '${m.id}',
		icon: '${m.icon}',
		category: '${m.category}',
		size: ${m.size},
		builtIn: ${m.builtIn ?? false},
		system: ${m.system ?? false},
		keywords: ${keywords},
		features: ${features},
		dependencies: ${deps},
	}`;
	});

	const content = `${header}
export const GENERATED_TOOLS: GeneratedToolMeta[] = [
${entries.join(',\n')}
];

export const TOOL_IDS = [${manifests.map(m => `'${m.id}'`).join(', ')}] as const;
export type GeneratedToolId = (typeof TOOL_IDS)[number];
`;

	fs.writeFileSync(OUTPUT_REGISTRY, content, 'utf-8');
	console.log(`✓ Generated registry: ${path.relative(process.cwd(), OUTPUT_REGISTRY)}`);
}

// Generate lazy loader map
function generateLoader(tools, manifests) {
	const header = `// AUTO-GENERATED - DO NOT EDIT
// Generated by: pnpm generate-registry
// Source: tools/*/panel.tsx

import { lazy } from 'react';

`;

	// Build tool-to-export map
	const toolExports = new Map();
	for (const tool of tools) {
		const exportName = detectPanelExport(tool.panelPath);
		toolExports.set(tool.id, exportName || toPascalCase(tool.id) + 'Panel');
	}

	const entries = manifests.map(m => {
		const exportName = toolExports.get(m.id) || toPascalCase(m.id) + 'Panel';
		return `\t'${m.id}': lazy(() => import('../tools/${m.id}/panel').then(m => ({ default: m.${exportName} })))`;
	});

	const content = `${header}export const generatedToolPanels = {
${entries.join(',\n')}
} as const;

export type LoadableToolId = keyof typeof generatedToolPanels;
`;

	fs.writeFileSync(OUTPUT_LOADER, content, 'utf-8');
	console.log(`✓ Generated loader: ${path.relative(process.cwd(), OUTPUT_LOADER)}`);
}

// Generate i18n aggregations
function generateI18n(tools) {
	const header = `// AUTO-GENERATED - DO NOT EDIT
// Generated by: pnpm generate-registry
// Source: tools/*/locales/{lang}.ts
`;

	const writeI18nFile = (lang, outputPath) => {
		const validTools = tools.filter(t => lang === 'en' ? t.hasEn : t.hasZh);
		
		const imports = validTools.map(t => {
			const variable = t.id.replace(/-/g, '_');
			return `import { ${lang} as ${variable} } from '../../tools/${t.id}/locales/${lang}';`;
		});

		const spread = validTools.map(t => {
			const variable = t.id.replace(/-/g, '_');
			return `\t...${variable},`;
		});

		const content = `${header}
${imports.join('\n')}

export const TOOLS_${lang.toUpperCase()} = {
${spread.join('\n')}
};
`;
		fs.writeFileSync(outputPath, content, 'utf-8');
		console.log(`✓ Generated i18n (${lang}): ${path.relative(process.cwd(), outputPath)}`);
	};

	writeI18nFile('en', OUTPUT_I18N_EN);
	writeI18nFile('zh', OUTPUT_I18N_ZH);
}

// Main
function main() {
	console.log('🔍 Scanning tool manifests...');
	const tools = discoverTools();
	
	if (tools.length === 0) {
		console.log('ℹ️ No tools with manifest.ts found. Creating sample manifest...');
		console.log('   Run this script again after adding manifest.ts to tools.');
		return;
	}

	const manifests = tools.map(t => parseManifest(t.manifestPath)).filter(Boolean);
	console.log(`📦 Found ${manifests.length}/${tools.length} valid manifests`);

	generateRegistry(tools, manifests);
	generateLoader(tools, manifests);
	generateI18n(tools);

	console.log('\n✨ Registry generation complete!');
	console.log(`   Tools with manifest: ${manifests.length}`);
	console.log(`   Tools without manifest: ${tools.length - manifests.length}`);
}

main();
