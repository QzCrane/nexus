#!/usr/bin/env node
// goal: Auto-generate tool registry from manifest files
// eff: Dual-scan tools/ and system/ -> generate registry, loader, i18n, permission map

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const HALO_ROOT = path.resolve(__dirname, '../apps/extension-halo/src');
const TOOLS_DIR = path.join(HALO_ROOT, 'tools');
const SYSTEM_DIR = path.join(HALO_ROOT, 'system');

const OUTPUT_REGISTRY = path.join(HALO_ROOT, 'kernel/registry/_generated.ts');
const OUTPUT_LOADER = path.join(HALO_ROOT, 'components/_generated-tool-loader.ts');
const OUTPUT_I18N_EN = path.join(HALO_ROOT, 'i18n/locales/_generated-tools-en.ts');
const OUTPUT_I18N_ZH = path.join(HALO_ROOT, 'i18n/locales/_generated-tools-zh.ts');

// Discover directory with manifest.json
function discoverTools(baseDir, type) {
	if (!fs.existsSync(baseDir)) return [];

	const dirs = fs.readdirSync(baseDir, { withFileTypes: true })
		.filter(d => d.isDirectory())
		.map(d => d.name);
	
	const modules = [];
	for (const dir of dirs) {
		const manifestPath = path.join(baseDir, dir, 'manifest.json');
		const panelPath = path.join(baseDir, dir, 'panel.tsx');
		const localesPath = path.join(baseDir, dir, 'locales');
		
		if (fs.existsSync(manifestPath) && fs.existsSync(panelPath)) {
			modules.push({ 
				id: dir, 
				type, // 'tools' or 'system'
				manifestPath, 
				panelPath,
				hasEn: fs.existsSync(path.join(localesPath, 'en.ts')),
				hasZh: fs.existsSync(path.join(localesPath, 'zh.ts'))
			});
		}
	}
	return modules;
}

// Parse manifest.json file
function parseManifest(filePath) {
	try {
		const content = fs.readFileSync(filePath, 'utf-8');
		return JSON.parse(content);
	} catch (e) {
		console.warn(`⚠️ Failed to parse: ${filePath}`, e.message);
		return null;
	}
}

// Detect panel export name from panel.tsx content
function detectPanelExport(panelPath) {
	try {
		const content = fs.readFileSync(panelPath, 'utf-8');
		// Match patterns like: export const XxxPanel or export function XxxPanel
		const match = content.match(/export\s+(?:const|function)\s+(\w+Panel)/);
		if (match) return match[1];
		// Fallback: match named export
		const namedMatch = content.match(/export\s*{\s*(\w+Panel)\s*}/);
		if (namedMatch) return namedMatch[1];
	} catch { /* ignore */ }
	return null;
}

// Convert kebab-case to PascalCase (fallback)
function toPascalCase(str) {
	return str.split('-').map(s => s.charAt(0).toUpperCase() + s.slice(1)).join('');
}

// Generate registry file
function generateRegistry(userModules, systemModules, manifestsMap) {
	const allModules = [...userModules, ...systemModules];

	const header = `// AUTO-GENERATED - DO NOT EDIT
// Generated by: pnpm generate-registry
// Source: tools/* and system/* manifests

import type { ToolCategory } from '../../i18n/types';

// Generated tool manifest interface
export interface GeneratedToolMeta {
	id: string;
	icon: string;
	category: ToolCategory;
	size: number;
	builtIn: boolean;
	system: boolean; // true = system functionality
	keywords: string[];
	features?: { contextMenu?: boolean; contentScript?: boolean; offscreen?: boolean };
	dependencies?: string[];
	permissions?: string[];
}
`;

	const generateEntry = (m) => {
		const manifest = manifestsMap.get(m.id);
		const features = manifest.features ? JSON.stringify(manifest.features) : 'undefined';
		const keywords = manifest.keywords ? JSON.stringify(manifest.keywords) : '[]';
		const deps = manifest.dependencies ? JSON.stringify(manifest.dependencies) : 'undefined';
		const permissions = manifest.permissions ? JSON.stringify(manifest.permissions) : '[]';

		return `\t{
		id: '${manifest.id}',
		icon: '${manifest.icon}',
		category: '${manifest.category}',
		size: ${manifest.size},
		builtIn: ${manifest.builtIn ?? false},
		system: ${manifest.system ?? false},
		keywords: ${keywords},
		features: ${features},
		dependencies: ${deps},
		permissions: ${permissions},
	}`;
	};

	// Permission Usage Map
	const permissionMap = {};
	for (const m of allModules) {
		const manifest = manifestsMap.get(m.id);
		if (manifest.permissions) {
			for (const p of manifest.permissions) {
				if (!permissionMap[p]) permissionMap[p] = [];
				permissionMap[p].push(m.id);
			}
		}
	}

	const content = `${header}
export const USER_TOOL_REGISTRY: GeneratedToolMeta[] = [
${userModules.map(generateEntry).join(',\n')}
];

export const SYSTEM_PLUGIN_REGISTRY: GeneratedToolMeta[] = [
${systemModules.map(generateEntry).join(',\n')}
];

export const ALL_APPS = [...USER_TOOL_REGISTRY, ...SYSTEM_PLUGIN_REGISTRY];

export const TOOL_IDS = [${allModules.map(m => `'${m.id}'`).join(', ')}] as const;
export type GeneratedToolId = (typeof TOOL_IDS)[number];

export const PERMISSION_USAGE_MAP: Record<string, string[]> = ${JSON.stringify(permissionMap, null, 4)};
`;

	fs.writeFileSync(OUTPUT_REGISTRY, content, 'utf-8');
	console.log(`✓ Generated registry: ${path.relative(process.cwd(), OUTPUT_REGISTRY)}`);
}

// Generate lazy loader map
function generateLoader(allModules, manifestsMap) {
	const header = `// AUTO-GENERATED - DO NOT EDIT
// Generated by: pnpm generate-registry
// Source: tools/*/panel.tsx and system/*/panel.tsx

import { lazy } from 'react';

`;

	// Build tool-to-export map
	const toolExports = new Map();
	for (const m of allModules) {
		const exportName = detectPanelExport(m.panelPath);
		toolExports.set(m.id, exportName || toPascalCase(m.id) + 'Panel');
	}

	const entries = allModules.map(m => {
		const exportName = toolExports.get(m.id) || toPascalCase(m.id) + 'Panel';
		const folder = m.type === 'system' ? 'system' : 'tools';
		return `\t'${m.id}': lazy(() => import('../${folder}/${m.id}/panel').then(m => ({ default: m.${exportName} })))`;
	});

	const content = `${header}export const generatedToolPanels = {
${entries.join(',\n')}
} as const;

export type LoadableToolId = keyof typeof generatedToolPanels;
`;

	fs.writeFileSync(OUTPUT_LOADER, content, 'utf-8');
	console.log(`✓ Generated loader: ${path.relative(process.cwd(), OUTPUT_LOADER)}`);
}

// Generate i18n aggregations
function generateI18n(allModules) {
	const header = `// AUTO-GENERATED - DO NOT EDIT
// Generated by: pnpm generate-registry
// Source: {tools,system}/*/locales/{lang}.ts
`;

	const writeI18nFile = (lang, outputPath) => {
		const validModules = allModules.filter(m => lang === 'en' ? m.hasEn : m.hasZh);
		
		const imports = validModules.map(m => {
			const variable = m.id.replace(/-/g, '_');
			const folder = m.type === 'system' ? 'system' : 'tools';
			return `import { ${lang} as ${variable} } from '../../${folder}/${m.id}/locales/${lang}';`;
		});

		const spread = validModules.map(m => {
			const variable = m.id.replace(/-/g, '_');
			return `\t...${variable},`;
		});

		const content = `${header}
${imports.join('\n')}

export const TOOLS_${lang.toUpperCase()} = {
${spread.join('\n')}
};
`;
		fs.writeFileSync(outputPath, content, 'utf-8');
		console.log(`✓ Generated i18n (${lang}): ${path.relative(process.cwd(), outputPath)}`);
	};

	writeI18nFile('en', OUTPUT_I18N_EN);
	writeI18nFile('zh', OUTPUT_I18N_ZH);
}

// Main
function main() {
	console.log('🔍 Scanning modules...');
	const userModules = discoverTools(TOOLS_DIR, 'tools');
	const systemModules = discoverTools(SYSTEM_DIR, 'system');
	const allModules = [...userModules, ...systemModules];
	
	if (allModules.length === 0) {
		console.log('ℹ️ No modules found.');
		return;
	}

	const dummyMap = new Map();
	allModules.forEach(m => {
		const manifest = parseManifest(m.manifestPath);
		if (manifest) dummyMap.set(m.id, manifest);
	});
	
	// Filter out invalid ones
	const validUserModules = userModules.filter(m => dummyMap.has(m.id));
	const validSystemModules = systemModules.filter(m => dummyMap.has(m.id));
	
	// Check strict isolation rules
	validUserModules.forEach(m => {
		const man = dummyMap.get(m.id);
		if (man.system === true) {
			console.error(`❌ Policy Violation: Tool '${m.id}' in src/tools has system:true!`);
			process.exit(1);
		}
	});

	validSystemModules.forEach(m => {
		const man = dummyMap.get(m.id);
		if (man.system !== true) {
			console.error(`❌ Policy Violation: System plugin '${m.id}' in src/system missing system:true!`);
			process.exit(1);
		}
	});

	console.log(`📦 Registry: ${validUserModules.length} Tools + ${validSystemModules.length} System Plugins`);

	generateRegistry(validUserModules, validSystemModules, dummyMap);
	generateLoader([...validUserModules, ...validSystemModules], dummyMap);
	generateI18n([...validUserModules, ...validSystemModules]);

	console.log('\n✨ Registry generation complete!');
}

main();
